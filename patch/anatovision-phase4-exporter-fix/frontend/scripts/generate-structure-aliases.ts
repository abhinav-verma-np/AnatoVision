/**
 * Automated structure -> manifest key mapping generator.
 *
 * Reads the REAL manifest.json and every KeyStructure across
 * lib/data/anatomy/*.ts, then computes SAFE, UNAMBIGUOUS matches using
 * word-set matching — never substring guessing, never one-off hand
 * mappings. A structure is only auto-mapped when exactly one manifest
 * key contains every word of its name; anything with zero or multiple
 * candidates is left for a human to review (never guessed).
 *
 * Usage:
 *   npm run generate-aliases
 *
 * Outputs:
 *   lib/data/generatedManifestAliases.ts  — safe auto-matches (regenerable)
 *   scripts/mapping-report.md             — everything that could NOT be
 *                                            safely auto-mapped, and why
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ANATOMY_SYSTEMS, type KeyStructure } from "../lib/data/anatomy";
import type { Manifest } from "../lib/manifest";

const ROOT = path.resolve(__dirname, "..");
const MANIFEST_PATH = path.join(ROOT, "public/models/manifest.json");
const OUTPUT_PATH = path.join(ROOT, "lib/data/generatedManifestAliases.ts");
const REPORT_PATH = path.join(ROOT, "scripts/mapping-report.md");

function loadManifestFile(): Manifest {
  const raw = readFileSync(MANIFEST_PATH, "utf-8");
  const data: unknown = JSON.parse(raw);
  if (typeof data !== "object" || data === null || Array.isArray(data)) {
    throw new Error(`${MANIFEST_PATH} is not a valid manifest object`);
  }
  return data as Manifest;
}

/** Split "bones-of-free-lower-limb" or "Vena Cava" into a word set. */
function wordSet(value: string): Set<string> {
  return new Set(
    value
      .toLowerCase()
      .split(/[^a-z0-9]+/)
      .filter(Boolean),
  );
}

interface AllStructure {
  systemId: string;
  structure: KeyStructure;
}

function collectStructures(): AllStructure[] {
  const all: AllStructure[] = [];
  for (const system of ANATOMY_SYSTEMS) {
    for (const structure of system.keyStructures) {
      all.push({ systemId: system.id, structure });
    }
  }
  return all;
}

interface MappingResult {
  generatedAliases: Record<string, string[]>;
  exactMatches: string[]; // structure ids already resolvable via id === manifest key
  autoMapped: Array<{ id: string; name: string; matchedKey: string }>;
  ambiguous: Array<{ id: string; name: string; candidates: string[] }>;
  unmapped: Array<{ id: string; name: string; systemId: string }>;
  claimedKeys: Set<string>;
}

function computeMapping(manifest: Manifest, structures: AllStructure[]): MappingResult {
  const manifestKeys = Object.keys(manifest);
  const manifestKeyWords = new Map(manifestKeys.map((k) => [k, wordSet(k)]));

  const generatedAliases: Record<string, string[]> = {};
  const exactMatches: string[] = [];
  const autoMapped: MappingResult["autoMapped"] = [];
  const ambiguous: MappingResult["ambiguous"] = [];
  const unmapped: MappingResult["unmapped"] = [];
  const claimedKeys = new Set<string>();

  for (const { systemId, structure } of structures) {
    // Tier 1: already resolvable via exact id match — no alias needed.
    if (manifest[structure.id]) {
      exactMatches.push(structure.id);
      claimedKeys.add(structure.id);
      continue;
    }

    const structureWords = wordSet(structure.name);
    if (structureWords.size === 0) {
      unmapped.push({ id: structure.id, name: structure.name, systemId });
      continue;
    }

    // A manifest key is a safe candidate only if EVERY word in the
    // structure's name appears in that key's own word set — whole-word
    // matching, never a loose substring check.
    const candidates = manifestKeys.filter((key) => {
      const keyWords = manifestKeyWords.get(key)!;
      for (const word of structureWords) {
        if (!keyWords.has(word)) return false;
      }
      return true;
    });

    if (candidates.length === 1) {
      const key = candidates[0]!;
      generatedAliases[structure.id] = [key];
      autoMapped.push({ id: structure.id, name: structure.name, matchedKey: key });
      claimedKeys.add(key);
    } else if (candidates.length > 1) {
      ambiguous.push({ id: structure.id, name: structure.name, candidates });
    } else {
      unmapped.push({ id: structure.id, name: structure.name, systemId });
    }
  }

  return { generatedAliases, exactMatches, autoMapped, ambiguous, unmapped, claimedKeys };
}

function writeGeneratedFile(result: MappingResult): void {
  const lines = [
    "/**",
    " * AUTO-GENERATED by scripts/generate-structure-aliases.ts — do not hand-edit.",
    " * Regenerate with: npm run generate-aliases",
    " *",
    " * Every entry here was matched algorithmically (whole-word match against",
    " * exactly one manifest key) — nothing here was typed in by hand.",
    " */",
    "",
    "export const GENERATED_MANIFEST_ALIASES: Record<string, string[]> = {",
    ...Object.entries(result.generatedAliases).map(
      ([id, aliases]) => `  ${JSON.stringify(id)}: ${JSON.stringify(aliases)},`,
    ),
    "};",
    "",
  ];
  writeFileSync(OUTPUT_PATH, lines.join("\n"), "utf-8");
}

function writeReport(manifest: Manifest, structures: AllStructure[], result: MappingResult): void {
  const manifestKeys = Object.keys(manifest);
  const unclaimedGlbs = manifestKeys.filter((k) => !result.claimedKeys.has(k));

  const lines: string[] = [
    "# Structure -> Manifest mapping report",
    "",
    `Generated: ${new Date().toISOString()}`,
    "",
    `- Manifest entries: ${manifestKeys.length}`,
    `- Curated structures: ${structures.length}`,
    `- Exact id matches: ${result.exactMatches.length}`,
    `- Auto-mapped (safe, unambiguous): ${result.autoMapped.length}`,
    `- Ambiguous (needs human review): ${result.ambiguous.length}`,
    `- Unmapped structures (no candidate found): ${result.unmapped.length}`,
    `- GLBs not claimed by any structure: ${unclaimedGlbs.length}`,
    "",
  ];

  if (result.autoMapped.length > 0) {
    lines.push("## Auto-mapped", "", "| Structure | id | Manifest key |", "| --- | --- | --- |");
    for (const m of result.autoMapped) {
      lines.push(`| ${m.name} | \`${m.id}\` | \`${m.matchedKey}\` |`);
    }
    lines.push("");
  }

  if (result.ambiguous.length > 0) {
    lines.push(
      "## Ambiguous — NOT auto-mapped, needs a manual `manifestAliases` entry",
      "",
      "| Structure | id | Candidate manifest keys | Reason |",
      "| --- | --- | --- | --- |",
    );
    for (const a of result.ambiguous) {
      lines.push(
        `| ${a.name} | \`${a.id}\` | ${a.candidates.map((c) => `\`${c}\``).join(", ")} | Multiple manifest keys contain every word of this structure's name — picking one automatically would risk showing the wrong model. |`,
      );
    }
    lines.push("");
  }

  if (result.unmapped.length > 0) {
    lines.push(
      "## Unmapped structures — no plausible manifest key found",
      "",
      "| Structure | id | System | Reason |",
      "| --- | --- | --- | --- |",
    );
    for (const u of result.unmapped) {
      lines.push(
        `| ${u.name} | \`${u.id}\` | ${u.systemId} | No manifest key contains all of this structure's name words. Either the model hasn't been exported yet, or Z-Anatomy names it differently. |`,
      );
    }
    lines.push("");
  }

  if (unclaimedGlbs.length > 0) {
    lines.push(
      "## GLBs not claimed by any current structure",
      "",
      "| GLB filename (manifest key) | Likely anatomy | Reason not mapped |",
      "| --- | --- | --- |",
    );
    for (const key of unclaimedGlbs) {
      lines.push(
        `| \`${key}\` | ${manifest[key]?.system ?? "unknown"} (best guess from folder) | No current KeyStructure's full name matches this key's words — likely a region/collection/duplicate not yet represented in lib/data/anatomy, or a naming style this generator's word-matching didn't anticipate. |`,
      );
    }
    lines.push("");
  }

  writeFileSync(REPORT_PATH, lines.join("\n"), "utf-8");
}

function main(): void {
  const manifest = loadManifestFile();
  const structures = collectStructures();
  const result = computeMapping(manifest, structures);

  writeGeneratedFile(result);
  writeReport(manifest, structures, result);

  console.log(`Manifest entries       : ${Object.keys(manifest).length}`);
  console.log(`Structures considered   : ${structures.length}`);
  console.log(`Exact id matches        : ${result.exactMatches.length}`);
  console.log(`Auto-mapped (safe)      : ${result.autoMapped.length}`);
  console.log(`Ambiguous (unmapped)    : ${result.ambiguous.length}`);
  console.log(`Unmapped (no candidate) : ${result.unmapped.length}`);
  console.log(`Report written to       : ${REPORT_PATH}`);
  console.log(`Aliases written to      : ${OUTPUT_PATH}`);
}

main();
